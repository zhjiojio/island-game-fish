const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'../..'),read=p=>JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const cfg=read('content/telemetry-scenes.json'),meta=read('content/meta.json'),nodes={};
for(const f of fs.readdirSync(path.join(root,'content/episodes')).filter(x=>x.endsWith('.json')).sort())Object.assign(nodes,read('content/episodes/'+f));
const keys=[],nodeInfo={},optionInfo={},optionIds={};
function add(k){keys.push(k)}
for(const [id,n]of Object.entries(nodes)){
 add('node_view:'+id);nodeInfo[id]={ep:n.ep,type:n.type||'story'};
 if(n.options){add('node_first_choice:'+id);add('node_first_commit:'+id);optionIds[id]=[];
  for(const [idx,o]of n.options.entries()){
   if(!o.id||optionInfo[o.id])throw Error('Missing/duplicate stable option id: '+id+' '+idx);
   optionIds[id].push(o.id);optionInfo[o.id]={nodeId:id,idx,ep:n.ep,text:o.text||'',next:o.next,hasAd:!!o.ad};
   for(const e of ['option_view','option_click','option_commit'])add(e+':'+o.id);
  }
 }
}
const chapterEvents=['card_view','card_click','chapter_enter','chapter_ready','chapter_complete','preview_view','preview_next','preview_replay','preview_home','chapter_ad_request','chapter_ad_ok','chapter_ad_fail'];
for(const c of meta.meta.homeChapters)for(const e of chapterEvents)add(e+':'+c.id);
for(const p of ['chapter_home','privacy','achievements','chapter_transition','achievement_detail'])add('page_view:'+p);
add('duration_exhausted');add('transport_issue');
// v90.20 · 成就详情浮层「看广告·直通该章」漏斗（每次启动去重 = UV 口径）
add('achievement_direct_click');add('achievement_direct_ok');add('achievement_direct_fail');
// v97.2 · 视频内嵌「拖拽解锁」互动漏斗（每次启动去重 = UV 口径）
//   arm   : 视频播到 pauseAt 暂停、引导层可见（分母）
//   try   : 手指在起点按下、真正进入拖拽（意图）
//   fail  : 抬手未通过三重校验（终点命中/路径覆盖/真实滑动），可重试
//   ok    : 通过校验、撒花庆祝并恢复播放（分子）
add('drag_unlock_arm');add('drag_unlock_try');add('drag_unlock_fail');add('drag_unlock_ok');
// v92.6 · 今日免广告通行证生效、跳过一次激励视频（维度 ad_slot 区分是哪个广告位被免掉）
//   用途：核对「看满 3 个后全局免广告」是否真的全链路生效，也用于估算被免掉的广告曝光量
add('ad_pass_skip');
// v92.7 · BE 结局页插屏广告（广告位 2300058116_03）。try=进入 BE 页触发调用，
//   close=插屏关闭或被频控/无填充跳过后放行。两者差值反映频控命中与填充率。
add('be_interstitial_try');add('be_interstitial_close');
for(let i=0;i<256;i++){
 const k='duration_slot:'+i;keys.push(k);
 if(!cfg.records[k]&&process.argv.includes('--allocate'))cfg.records[k]={id:20000+i,status:'active'};
}
const used=new Set();for(const [k,v]of Object.entries(cfg.records)){
 if(used.has(v.id))throw Error('Duplicate scene ID '+v.id);used.add(v.id);
 if(v.status==='active'&&!keys.includes(k))v.status='retired';
}
for(const k of keys){
 if(!cfg.records[k]){
  if(!process.argv.includes('--allocate'))throw Error('Unregistered scene '+k+'; explicitly allocate append-only IDs');
  while(used.has(cfg.nextId))cfg.nextId++;
  if(cfg.nextId>=20000)throw Error('Scene range exhausted');
  cfg.records[k]={id:cfg.nextId++,status:'active'};used.add(cfg.records[k].id);
 }else if(cfg.records[k].status==='retired')throw Error('Retired key reused: '+k);
}
if(process.argv.includes('--allocate'))fs.writeFileSync(path.join(root,'content/telemetry-scenes.json'),JSON.stringify(cfg,null,2)+'\n');
const byKey={};for(const[k,v]of Object.entries(cfg.records))if(v.status!=='retired')byKey[k]=v.id;
const out={schemaVersion:cfg.schemaVersion,gameVersion:meta.version,byKey,nodeInfo,optionInfo,optionIds,durationSlots:256};
fs.writeFileSync(path.join(root,'package/js/telemetry-manifest.js'),'// AUTO-GENERATED by build-telemetry.cjs; edit content/telemetry-scenes.json\n(function(g){g.TelemetryManifest='+JSON.stringify(out)+';})(typeof GameGlobal!=="undefined"?GameGlobal:window);\n');
const rows=['scene_id,event_key,status,game_version,node_id,option_id,ep,text'];
const csv=x=>'"'+String(x??'').replaceAll('"','""')+'"';
for(const[k,v]of Object.entries(cfg.records).sort((a,b)=>a[1].id-b[1].id)){
 const [e,id]=k.split(':'),o=optionInfo[id],n=nodeInfo[id];rows.push([v.id,k,v.status,meta.version,o?.nodeId||((e.startsWith('node_'))?id:''),o?id:'',o?.ep||n?.ep||(/^EP\d+$/.test(id)?id:''),o?.text||''].map(csv).join(','));
}
fs.writeFileSync(path.join(root,'docs/telemetry-scenes.csv'),rows.join('\n')+'\n');
console.log('Telemetry manifest:',Object.keys(nodes).length,'nodes,',Object.keys(optionInfo).length,'options,',keys.length,'active keys, 256 bounded duration slots');
