#!/usr/bin/env python3
"""Build video-bound subtitles from content/subtitles/verified, never script SRT.
A new video filename requires its own ASR record. Spelling corrections inherit
character times; no legacy suffix fallback or whole-video synthetic timing.
"""
import json, re, sys, unicodedata
from pathlib import Path
from urllib.parse import urlsplit
REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / 'package/js/subtitles.js'

def spoken(ch):
    return not (ch.isspace() or unicodedata.category(ch)[0] in ('P', 'Z'))

def align(text, raw_chars, duration):
    target = [(i,ch) for i,ch in enumerate(text) if spoken(ch)]
    raw = [c for c in raw_chars if spoken(c[2])]
    if not target: return []
    if not raw: raise ValueError('nonempty transcript without ASR timing')
    n,m = len(target),len(raw)
    dp = [[0]*(m+1) for _ in range(n+1)]
    for i in range(n+1): dp[i][0]=i
    for j in range(m+1): dp[0][j]=j
    for i in range(1,n+1):
        for j in range(1,m+1):
            dp[i][j]=min(dp[i-1][j-1]+(target[i-1][1]!=raw[j-1][2]),dp[i-1][j]+1,dp[i][j-1]+1)
    slots=[None]*n; i,j=n,m
    while i or j:
        if i and j and dp[i][j]==dp[i-1][j-1]+(target[i-1][1]!=raw[j-1][2]):
            slots[i-1]=raw[j-1][:2];i-=1;j-=1
        elif j and dp[i][j]==dp[i][j-1]+1: j-=1
        else: i-=1
    for i in range(n):
        if slots[i] is not None: continue
        right=next((j for j in range(i+1,n) if slots[j] is not None),n)
        start=slots[i-1][1] if i else raw[0][0]
        end=max(start,slots[right][0] if right<n else raw[-1][1]);count=right-i
        for j in range(i,right): slots[j]=[start+(end-start)*(j-i)/count,start+(end-start)*(j-i+1)/count]
    timing={position:pair for (position,_),pair in zip(target,slots)}
    result=[];prev=raw[0][0]
    for i,ch in enumerate(text):
        pair=timing.get(i,[prev,prev]);start=max(prev,min(duration,pair[0]));end=max(start,min(duration,pair[1]))
        result.append([round(start,3),round(end,3),ch]);prev=end
    return result

def build_entry(record):
    duration=record['duration'];text=record['transcript'];chars=align(text,record['asrChars'],duration)
    segments=[];start=0
    for i,ch in enumerate(text):
        gap=i+1<len(chars) and chars[i+1][0]-chars[i][1]>0.65
        if ch in '。！？!?…' or gap or i==len(text)-1:
            part=chars[start:i+1]
            if any(spoken(c[2]) for c in part): segments.append([part[0][0],part[-1][1],''.join(c[2] for c in part),part])
            start=i+1
    return {'d':duration,'s':segments,'status':record['status'],'speakerKey':record.get('speakerKey'),'speakerRuleKey':record.get('speakerRuleKey'),'sha256':record['sha256']}

def collect(repo=REPO):
    records={}
    for path in sorted((repo/'content/subtitles/verified').glob('*.json')):
        record=json.loads(path.read_text());key=Path(urlsplit(record['url']).path).stem
        if path.stem!=key or key in records: raise ValueError(f'conflicting subtitle key: {path}')
        if not re.fullmatch('[a-f0-9]{64}',record.get('sha256','')): raise ValueError(f'missing video hash: {key}')
        if record.get('status') not in ('speech','no_audio','no_speech','nonverbal','partial_review','unclear_audio'): raise ValueError(f'unknown status: {key}')
        if record['duration']<=0: raise ValueError(f'invalid duration: {key}')
        if not record['transcript'] and record['status'] in ('speech','partial_review'): raise ValueError(f'missing speech transcript: {key}')
        records[key]=record
    live=set()
    for path in (repo/'content/episodes').glob('EP*.json'):
        for node in json.loads(path.read_text()).values():
            media=node.get('media',{})
            if media.get('kind')=='video': live.add(media['file'])
    missing=[]
    for url in sorted(live):
        key=Path(urlsplit(url).path).stem
        if key not in records or records[key]['url']!=url: missing.append(url)
    if missing:
        print(f'WARN: {len(missing)} live videos without matching ASR source (skipped, no subtitles):', file=sys.stderr)
        for url in missing: print('  - '+Path(urlsplit(url).path).stem, file=sys.stderr)
    resolved=[url for url in sorted(live) if Path(urlsplit(url).path).stem in records
              and records[Path(urlsplit(url).path).stem]['url']==url]
    return {Path(urlsplit(url).path).stem:records[Path(urlsplit(url).path).stem] for url in resolved}

def main():
    records=collect();data={key:build_entry(record) for key,record in records.items()}
    payload=json.dumps(data,ensure_ascii=False,separators=(',',':'))
    js='''// AUTO-GENERATED by scripts/subtitles/build_subtitles_js.py
// Source: content/subtitles/verified/*.json. Text and timing follow actual video audio.
(function(g){
  var DATA = PAYLOAD;
  function keyFromUrl(url) {
    var m = String(url || '').split(/[?#]/)[0].match(/([^/]+)\\.mp4$/i);
    return m ? m[1] : null;
  }
  function get(url) { return DATA[keyFromUrl(url)] || null; }
  g.SUBTITLES = {data:DATA, get:get, keyFromUrl:keyFromUrl};
})(typeof GameGlobal !== 'undefined' ? GameGlobal : (typeof window !== 'undefined' ? window : globalThis));
'''.replace('PAYLOAD',payload)
    OUTPUT.parent.mkdir(parents=True,exist_ok=True);OUTPUT.write_text(js)
    print(f'Built {len(data)} video subtitle records -> {OUTPUT} ({len(js.encode()):,} bytes)')
    reviews=[key for key,value in records.items() if value['status'] in ('partial_review','unclear_audio')]
    if reviews: print('Audio requiring listening review: '+', '.join(reviews))
    return 0
if __name__=='__main__': sys.exit(main())
